#!/usr/bin/env python3
"""
SETU v5 - Fitted override learning on SYNTHETIC override logs.
=====================================================================================
The live engine is unchanged: BKT with hand-set priors plus the v4 hand-set
override shrinkage. This script asks a narrower question: IF teachers override
the way our hand-set policy assumes, does the override LOG carry enough signal
for a fitted model to predict the override from observable class statistics?

WHAT THIS DOES:
  1. Simulates K concepts, each with a hidden "confusion level" theta.
  2. For each concept, simulates M override events: a teacher watches n
     synthetic students (correct with probability driven by theta), then
     overrides by a noisy threshold policy: high observed mastery ->
     mark_cleared, low -> reinforce, middle -> assign_concept.
  3. Fits a logistic regression (pure Python gradient descent, stdlib only)
     to predict mark_cleared vs reinforce from [observed_mean, n_students,
     frac_changed_mind] - no deep learning, no external data.
  4. Splits HELD-OUT BY CONCEPT (80/20): no concept appears in both train and
     test, so the model must generalise to unseen concepts.
  5. Reports held-out accuracy, log-loss and AUC, plus a majority-class
     baseline for honesty.

HONESTY CONTRACT (do not remove):
  - EVERY override here is SYNTHETIC, generated by the same hand-set policy
    family the v4 shrinkage targets encode. Real teachers may override for
    reasons no feature captures. This number is NOT a classroom result.
  - The live system does NOT use this fitted model. It is evidence that the
    log format is learnable, nothing more.

Run:      python setu_override_fit.py [--concepts 60] [--events 30] [--seed 7]
"""

import argparse
import json
import math
import random

LABEL = "SYNTHETIC OVERRIDES - generated by a hand-set teacher policy. Not a classroom result. Live engine unchanged."


def simulate(concepts, events, seed):
    rng = random.Random(seed)
    rows = []  # (concept_id, features, label)
    for c in range(concepts):
        cid = f"syn_concept_{c:03d}"
        theta = rng.betavariate(2.0, 2.0)  # hidden confusion level in [0,1]
        for e in range(events):
            n = rng.choice([10, 15, 20, 25])
            # students correct with prob (1-theta)*0.9 + small guess mass
            p_correct = min(0.99, max(0.01, (1.0 - theta) * 0.9 + 0.05))
            obs = sum(1 for _ in range(n) if rng.random() < p_correct) / n
            # noisy teacher policy
            noisy = obs + rng.gauss(0.0, 0.08)
            if noisy > 0.65:
                action = "mark_cleared"
            elif noisy < 0.45:
                action = "reinforce"
            else:
                action = "assign_concept"
            if action == "assign_concept":
                continue  # binary task: cleared vs reinforce
            label = 1 if action == "mark_cleared" else 0
            frac_changed = rng.betavariate(2, 8)  # share of students the teacher re-checked
            rows.append((cid, [obs, n / 25.0, frac_changed], label))
    return rows


def sigmoid(z):
    if z >= 0:
        return 1.0 / (1.0 + math.exp(-z))
    e = math.exp(z)
    return e / (1.0 + e)


def fit_logistic(train, epochs=300, rate=0.5, l2=1e-4):
    d = len(train[0][1])
    w = [0.0] * (d + 1)  # + bias
    for _ in range(epochs):
        grad = [0.0] * (d + 1)
        for _, x, y in train:
            z = w[0] + sum(w[i + 1] * x[i] for i in range(d))
            p = sigmoid(z)
            err = p - y
            grad[0] += err
            for i in range(d):
                grad[i + 1] += err * x[i]
        m = len(train)
        w[0] -= rate * grad[0] / m
        for i in range(d):
            w[i + 1] -= rate * (grad[i + 1] / m + l2 * w[i + 1])
    return w


def evaluate(w, rows):
    d = len(rows[0][1])
    correct = 0
    ll = 0.0
    scored = []
    for _, x, y in rows:
        p = sigmoid(w[0] + sum(w[i + 1] * x[i] for i in range(d)))
        p = min(1 - 1e-9, max(1e-9, p))
        correct += 1 if (p >= 0.5) == bool(y) else 0
        ll -= y * math.log(p) + (1 - y) * math.log(1 - p)
        scored.append((p, y))
    # AUC by rank
    scored.sort()
    pos = sum(y for _, _, y in rows)
    neg = len(rows) - pos
    auc = None
    if pos and neg:
        rank_sum = sum(i + 1 for i, (_, y) in enumerate(scored) if y == 1)
        auc = (rank_sum - pos * (pos + 1) / 2) / (pos * neg)
    return {
        "accuracy": round(correct / len(rows), 4),
        "log_loss": round(ll / len(rows), 4),
        "auc": round(auc, 4) if auc is not None else None,
    }


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--concepts", type=int, default=60)
    ap.add_argument("--events", type=int, default=30)
    ap.add_argument("--seed", type=int, default=7)
    args = ap.parse_args()

    rows = simulate(args.concepts, args.events, args.seed)
    by_concept = {}
    for cid, x, y in rows:
        by_concept.setdefault(cid, []).append((cid, x, y))
    concepts = sorted(by_concept)
    # held-out split BY CONCEPT (no leakage), deterministic
    cut = max(1, int(len(concepts) * 0.8))
    train = [r for c in concepts[:cut] for r in by_concept[c]]
    test = [r for c in concepts[cut:] for r in by_concept[c]]

    w = fit_logistic(train)
    metrics = evaluate(w, test)

    majority = max(sum(y for _, _, y in test), len(test) - sum(y for _, _, y in test)) / len(test)

    print(json.dumps({
        "label": LABEL,
        "task": "predict mark_cleared (1) vs reinforce (0) from class statistics",
        "model": "logistic regression, pure Python, no external data",
        "split": "held-out BY CONCEPT (80/20) - no concept in both train and test",
        "seed": args.seed,
        "concepts_total": args.concepts,
        "events_per_concept": args.events,
        "train_rows": len(train),
        "test_rows": len(test),
        "heldout": metrics,
        "majority_baseline_accuracy": round(majority, 4),
    }, indent=1))


if __name__ == "__main__":
    main()
